-- Slash commands, the guild roster, and the dev probes.
return function(test, H)
    local eq, ok, no, match = H.eq, H.ok, H.no, H.match

    test("help lists the commands; unknown commands show help", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord")
        c:Slash("")
        ok(c:Printed("dev commands:"))
        ok(c:Printed("/dp adopt [name]", true))
        no(c:Printed("/dp claim", true), "the old names work but aren't listed")
        c:ClearPrinted()
        c:Slash("bogus stuff")
        ok(c:Printed("/dp letgo", true))
        eq(c.env.SLASH_DYREPARKEN1, "/dp")
        eq(c.env.SLASH_DYREPARKEN2, "/dyreparken")
        c.env.SlashCmdList.DYREPARKEN(nil)
    end)

    test("claim by name: exact before partial, case-insensitive", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord", { pets = { 42, 40 }, summoned = false })
        w:Run(12)
        c:Slash("claim")
        ok(c:Printed("Summon the companion you want, or give its name."))
        c:Slash("claim Hamster")
        ok(c:Printed('You have no companion matching "Hamster".'))
        c:Slash("claim BOMBAY CAT")
        eq(c.ns.Registry:MyPet(), "s:40")
        c:Slash("claim tabby")
        eq(c.ns.Registry:MyPet(), "s:42")
        ok(c:Printed("You adopted Black Tabby Cat (and let Bombay Cat go).", true))
        local key = c.ns.Pets:FindOwned("cat")
        ok(key == "s:40" or key == "s:42")
    end)

    test("list shows reservations with nicknames, sorted by pet", function()
        local w = H.World()
        local ola = w:AddClient("Ola Nord", { pets = { 5159 } })
        local kari = w:AddClient("Kari Berg", { pets = { 40 } })
        w:Run(20)
        ola:Slash("claim"); kari:Slash("claim")
        w:SkipDays(7)
        kari:Slash("nick Mjau")
        w:Run(1)
        ola:ClearPrinted()
        ola:Slash("list")
        eq(ola.printed[1], "Dyreparken: The guild cares for 2 of 83 companions (2%):")
        eq(ola.printed[2], 'Dyreparken:   Bombay Cat - Kari Berg ("Mjau")')
        eq(ola.printed[3], "Dyreparken:   Panda Cub - Ola Nord")
    end)

    test("nick and release from the command line", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord")
        w:Run(12)
        c:Slash("nick Early")
        ok(c:Printed("You haven't adopted a companion."))
        c:Slash("claim")
        w:SkipDays(7)
        c:Slash("nick Mr Bambus")
        eq(c.ns.Registry:MyRecord().n, "Mr Bambus", "keeps its case")
        c:Slash("nick")
        eq(c.ns.Registry:MyRecord().n, nil)
        c:Slash("letgo")
        ok(c:Printed("You let Panda Cub go."))
        c:Slash("adopt panda")
        ok(c:Printed("You adopted Panda Cub."))
        c:Slash("release") -- the old name still works
        ok(c:Printed("You let Panda Cub go."))
        c:Slash("letgo")
        ok(c:Printed("You haven't adopted a companion."))
    end)

    test("pet keys and names", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord", { pets = { 5159 } })
        local P = c.ns.Pets
        eq(P:KeyOf(c:GuidOf(5159)), "s:5159")
        eq(P:KeyOf(nil), nil)
        eq(P:KeyOf("BattlePet-0-BOGUS"), nil, "the journal throws for unknown GUIDs")
        eq(P:SpeciesOfKey("s:46"), 46)
        eq(P:SpeciesOfKey("n:Panda"), nil)
        eq(P:SpeciesOfKey(nil), nil)
        eq(P:KeyOfSpecies(nil), nil)
        eq(P:NameOfKey("s:46"), "White Kitten")
        eq(P:NameOfKey("s:99999"), "s:99999", "unknown species: the key")
        eq(P:NameOfKey("n:Old Pet"), "Old Pet")
        eq(P:IconOfKey("s:46"), 1046)
        eq(P:IconOfKey("n:x"), nil)
    end)

    test("a journal without species IDs falls back to names", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord", { pets = { 5159 } })
        c.noSpeciesID = true
        eq(c.ns.Pets:KeyOf(c:GuidOf(5159)), "n:Panda Cub")
    end)

    test("a journal without GetOwnedPetIDs is read by index", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord", { pets = { 5159, 46 }, patch = function(env)
            env.C_PetJournal.GetOwnedPetIDs = nil
        end })
        c.journalList = { { guid = c:GuidOf(5159), sid = 5159, owned = true }, { sid = 40, owned = false },
            { guid = c:GuidOf(46), sid = 46, owned = true } }
        local owned = c.ns.Pets:Owned()
        ok(owned["s:5159"] and owned["s:46"])
        no(owned["s:40"])
    end)

    test("probe and probe more run with and without a pet or target", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord")
        w:AddMember("Per Hansen", 3)
        w:Run(12)
        c:Slash("probe")
        ok(c:Printed("build: 1.60.1, 70790"))
        ok(c:Printed("summoned BattlePet"))
        c:Slash("probe more")
        ok(c:Printed("No target: target a companion"))
        ok(c:Printed('roster offline 2: name="Per Hansen"', true))
        c:OpenJournal({ extra = { 40 } })
        c.units.target = { companion = true, species = 46, name = "White Kitten",
            lines = { { leftText = "White Kitten" }, { leftText = "Kari Berg's Companion" } } }
        c:Slash("probe more")
        ok(c:Printed("owner from tooltip: Kari Berg"))
        ok(c:Printed("target tooltip 2: Kari Berg's Companion"))
        ok(c:Printed("list buttons visible: 2"))
        c:Summon(nil)
        c:Slash("probe")
        ok(c:Printed("No companion summoned"))
        c.units.target.species = nil
        c:Slash("probe more")
        eq(#c:Log("Probe"), #c:Log("Probe"))
    end)

    test("guild roster: on demand, throttled, with a fallback when ignored", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord")
        w:AddMember("Kari Berg", 2)
        local G = c.ns.Guild
        eq(G:IsMember("Kari Berg"), nil, "nothing known before the first roster")
        w:Run(11)
        eq(c.rosterRequests, 1, "requested at login")
        ok(G.complete)
        eq(G:IsMember("Kari Berg"), true)
        eq(G:IsMember("Nobody Here"), false)
        eq(G:DaysOffline("Kari Berg"), 2)
        eq(G:DaysOffline("Ola Nord"), 0, "online")
        G:Refresh()
        eq(c.rosterRequests, 1, "fresh enough")
        c.rosterIgnored = true
        G:Refresh(true)
        G:Refresh(true)
        eq(c.rosterRequests, 2, "one request at a time")
        w:Run(16)
        eq(#c:Log("roster: 2/2 rows"), 2, "read anyway after the fallback timeout")
        local lone = w:AddClient("Per Hansen", { guild = false })
        lone.ns.Guild:Refresh(true)
        eq(lone.rosterRequests, nil)
    end)

    test("the fallback doesn't read an empty roster", function()
        local w = H.World()
        local c = w:AddClient("Ola Nord")
        c.rosterIgnored = true
        w:RemoveMember("Ola Nord")
        c.guild = w.guildName -- still "in" a guild whose roster isn't loaded
        w:Run(30)
        eq(#c:Log("roster:"), 0)
    end)
end
