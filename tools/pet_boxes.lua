-- Writes Data/PetBoxes.lua from a /dp probe api boxes run (2026-11-16, Moves.FRAMING):
--   luajit tools/pet_boxes.lua [path to SavedVariables/Dyreparken.lua]
-- (default: the NIKKERN account's). Merged: the species the run measured are written anew, every other line in
-- the file is kept, so a run of only new species ("boxes <ids>") is enough. A species the run couldn't read
-- (no scene, no box) keeps its old line, if any.
local path = arg[1] or ".wow/WTF/Account/NIKKERN/SavedVariables/Dyreparken.lua"
if not arg[1] and not io.open(path) then path = "../../../WTF/Account/NIKKERN/SavedVariables/Dyreparken.lua" end
local chunk = assert(loadfile(path))
chunk()
local data = assert(DyreparkenDebugDB and DyreparkenDebugDB.petBoxes, "no petBoxes: run /dp probe api boxes and /reload")

local names = {}
for line in io.lines("Data/Companions.lua") do
    local sid, name = line:match("^%s*%[(%d+)%] = .-%-%- (.+)$")
    if sid then names[tonumber(sid)] = name end
end

local old = {}
if io.open("Data/PetBoxes.lua") then
    local ns = {}
    assert(loadfile("Data/PetBoxes.lua"))("Dyreparken", ns)
    old = ns.PetBoxes or {}
end

local rows, ids, seen = {}, {}, {}
local fresh, kept, failed = 0, 0, 0
for sid, b in pairs(data) do
    if b.low and b.high and b.scene then rows[sid] = b; fresh = fresh + 1 else failed = failed + 1 end
end
for sid, b in pairs(old) do if not rows[sid] then rows[sid] = b; kept = kept + 1 end end
for sid in pairs(rows) do if not seen[sid] then seen[sid] = true; ids[#ids + 1] = sid end end
table.sort(ids)

local lines = {}
for _, sid in ipairs(ids) do
    local b = rows[sid]
    lines[#lines + 1] = ("    [%d] = { scene = %d, low = %.3f, high = %.3f, wide = %.3f },  -- %s"):format(sid, b.scene,
        b.low, b.high, b.wide, names[sid] or "?")
end
local out = assert(io.open("Data/PetBoxes.lua", "w"))
out:write([[
---@class Dyreparken
local ns = select(2, ...)

-- GENERATED by luajit tools/pet_boxes.lua from a /dp probe api boxes run. Don't edit.
-- Every species' standing box in its model scene (Menagerie/Moves.lua, Moves.FRAMING): the scene id, the
-- model's lowest and highest point standing and its widest side, in model units.
ns.PetBoxes = {
]] .. table.concat(lines, "\n") .. (#lines > 0 and "\n" or "") .. "}\n")
out:close()
print(("Data/PetBoxes.lua: %d species measured, %d kept from the file, %d the run couldn't read"):format(fresh, kept, failed))
