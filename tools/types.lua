-- The namespace's fields for the Lua language server (2026-11-15, docs/RESEARCH.md: Lua practices 3 and 4).
--
--   luajit tools/types.lua            writes tools/types/ns.lua (tools/check.sh does, then checks the code)
--
-- Every file starts `---@class Dyreparken` / `local ns = select(2, ...)`: one class, defined in parts, so
-- `function ns.Print` in Init.lua is a field everyone sees. A plain assignment (`ns.Wire = Wire`) doesn't
-- define one for the language server, so this lists them, found in the code: a module (`local Wish = {}`
-- under `---@class Dyreparken.Wish`) by its class, so `ns.Wish:Grnat()` is caught; anything else as `any`.
-- So `ns.Bodn` (no such field) is caught everywhere; a new module needs nothing but its `---@class` line.
local files = {}
for line in io.popen("git ls-files '*.lua'"):lines() do
    if not line:match("^Libs/") and not line:match("^tools/") then files[#files + 1] = line end
end
table.sort(files)

local fields, order = {}, {}
local strings, sorder = {}, {} -- the client's global strings read as _G.NAME (Blizzard's GlobalStrings)
for _, f in ipairs(files) do
    local text = assert(io.open(f)):read("*a")
    for name in text:gmatch("_G%.([%u_][%u%d_]*)") do
        if not strings[name] then strings[name] = true; sorder[#sorder + 1] = name end
    end
    for name, rhs in text:gmatch("\nns%.([%a_][%w_]*)%s*=%s*([^\n]*)") do
        local loc = rhs:match("^([%a_][%w_]*)%s*$")
        local class = loc and text:find("%-%-%-@class Dyreparken%." .. name .. "\nlocal " .. loc .. " =") and
            ("Dyreparken." .. name)
        if not fields[name] then order[#order + 1] = name end
        if class or not fields[name] then fields[name] = { class or "any", f } end
    end
end
table.sort(order)

local out = { "---@meta", "-- GENERATED by tools/types.lua from the code; don't edit.", "", "---@class Dyreparken" }
for _, name in ipairs(order) do
    out[#out + 1] = ("---@field %s %s %s"):format(name, fields[name][1], fields[name][2])
end
table.sort(sorder)
out[#out + 1] = ""
for _, name in ipairs(sorder) do out[#out + 1] = ("---@type string\n%s = nil"):format(name) end
os.execute("mkdir -p tools/types")
local f = assert(io.open("tools/types/ns.lua", "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
