-- luacheck's config, built from the test harness's stub client (2026-11-15, docs/RESEARCH.md: Lua
-- practices 1 and 2). One list of the client API, the stubs': an API the addon starts using must be
-- stubbed (tools/test/harness/env/*.lua) before lint accepts it, as the tests already demand.
--
--   luajit tools/lint_config.lua > <file>; luacheck --config <file> .     (tools/check.sh does both)
--
-- The C_* namespaces are listed with their fields, so C_PetJournal.GetPetInfoBySpeciesId (a wrong case)
-- is caught; frames and other tables are taken whole (their methods are the stubs' frame types').
package.path = "tools/test/?.lua;" .. package.path
local H = require("harness")

local w = H.World()
local c = w:AddClient("Lint Klient")
w:Run(5)
c:OpenJournal() -- (Blizzard's Collections code makes its frames and functions then: PetJournal, PetJournalPetCard...)
local env = c:BuildEnv()
for k, v in pairs(c.env) do
    if rawget(env, k) == nil and type(k) == "string" and not k:match("^Dyreparken") and not k:match("^SLASH_") then
        env[k] = v
    end
end

-- Read, but only behind a check that they exist (Forever lacks some, the probes ask): not stubbed on
-- purpose, so the tests run without them as Forever does.
local OPTIONAL = {
    "GetAddOnMetadata",      -- Init: C_AddOns.GetAddOnMetadata first
    "ScrollUtil",            -- JournalUI, PetsProbe: the journal's list on a newer client
    "C_PetBattles",          -- PetFrame: hidden in a pet battle, if the client has them
    "BugGrabber",            -- Dev/Errors: the other addon, when loaded
    "C_AddOnProfiler",       -- Dev/Perf
    "C_SpecializationInfo", "GetNumSpecializations", -- Dev/ApiProbe: what the client has
    "GetRealZoneText", "GetMinimapZoneText", "IsIndoors", "IsCurrentSpell", "IsAutoRepeatSpell",
}
local OPTIONAL_FIELDS = { C_ChatInfo = { "SendChatMessage" }, C_ClassTalents = { "HasUnspentTalentPoints" } }
local OURS = { DyreparkenDB = true, DyreparkenDebugDB = true, DyreparkenCharDB = true, SlashCmdList = true,
    StaticPopupDialogs = true }
for _, k in ipairs(OPTIONAL) do if env[k] == nil then env[k] = true end end

local plain, spaced = {}, {}
for k, v in pairs(env) do
    if type(k) == "string" and k:match("^[%a_][%w_]*$") and k ~= "_G" and not OURS[k] then
        if type(v) == "table" and k:match("^C_") then
            local fields = {}
            for f in pairs(v) do if type(f) == "string" then fields[#fields + 1] = f end end
            for _, f in ipairs(OPTIONAL_FIELDS[k] or {}) do if v[f] == nil then fields[#fields + 1] = f end end
            table.sort(fields)
            spaced[#spaced + 1] = { k, fields }
        else
            plain[#plain + 1] = k
        end
    end
end
table.sort(plain)
table.sort(spaced, function(a, b) return a[1] < b[1] end)

local out = {}
local function P(s) out[#out + 1] = s end
P("-- GENERATED by tools/lint_config.lua from the harness's stubs; don't edit.")
P('std = "lua51"')
P("max_line_length = false")
-- Libs/ are others' code; tools/ run on the desktop (luajit, with io and os), Dev/ in game like the rest.
P('exclude_files = { "Libs/**", "tools/**", ".claude/**" }')
-- Ours: the SavedVariables (the TOC) and what Blizzard's frames and slash commands read back.
P('globals = { "DyreparkenDB", "DyreparkenDebugDB", "DyreparkenCharDB", "SlashCmdList", "StaticPopupDialogs",')
P('    "SLASH_DYREPARKEN1", "SLASH_DYREPARKEN2", "SLASH_DYREPARKENKLAPP1" }')
-- LibStub: Libs/ (left out) makes it.
P("read_globals = {")
P('    "LibStub",')
for _, k in ipairs(plain) do P(("    %q,"):format(k)) end
for _, e in ipairs(spaced) do
    local f = {}
    for _, x in ipairs(e[2]) do f[#f + 1] = ("%q"):format(x) end
    P(("    %s = { fields = { %s } },"):format(e[1], table.concat(f, ", ")))
end
P("}")
-- Everything but: unused arguments (212: handlers and callbacks take what the client passes), values
-- overwritten or unused (31x: the probes' and Decor's defaults on purpose), shadowing (4xx: `self` in
-- nested methods, short names in long files). The rest found 3 small things on its first run (2026-11-15).
P('ignore = { "212", "31.", "4.." }')
io.write(table.concat(out, "\n"), "\n")
