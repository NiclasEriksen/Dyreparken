-- Writes Data/AnimLengths.lua from a /dp probe api lengths run:
--   luajit tools/anim_lengths.lua [path to SavedVariables/Dyreparken.lua]
-- (default: the NIKKERN account's). Keeps a species' one-off lengths that differ from its
-- Stand's (an id the model lacks plays Stand instead, and that length means nothing) and
-- leaves out "none" (no end within the probe's time-out: a loop or a held pose).
local path = arg[1] or "../../../WTF/Account/NIKKERN/SavedVariables/Dyreparken.lua"
local chunk = assert(loadfile(path))
chunk()
local data = assert(DyreparkenDebugDB and DyreparkenDebugDB.animLengths, "no animLengths: run /dp probe api lengths and /reload")

local names = {}
for line in io.lines("Data/Companions.lua") do
    local sid, name = line:match("^%s*%[(%d+)%] = .-%-%- (.+)$")
    if sid then names[tonumber(sid)] = name end
end

local ids = {}
for sid in pairs(data) do ids[#ids + 1] = sid end
table.sort(ids)
local lines, kept, dropped = {}, 0, 0
for _, sid in ipairs(ids) do
    local own, stand = data[sid], data[sid][0]
    local parts = {}
    local anims = {}
    for id, len in pairs(own) do if type(id) == "number" and id ~= 0 then anims[#anims + 1] = id end end
    table.sort(anims)
    for _, id in ipairs(anims) do
        local len = own[id]
        if type(len) == "number" and len > 0.05 and not (stand and math.abs(len - stand) < 0.02) then
            parts[#parts + 1] = ("[%d] = %.2f"):format(id, len)
            kept = kept + 1
        else
            dropped = dropped + 1
        end
    end
    if #parts > 0 then
        lines[#lines + 1] = ("    [%d] = { %s },  -- %s"):format(sid, table.concat(parts, ", "), names[sid] or "?")
    end
end

local f = assert(io.open("Data/AnimLengths.lua", "w"))
f:write([[local _, ns = ...

-- GENERATED by tools/anim_lengths.lua from /dp probe lengths (DyreparkenDebugDB.animLengths). Don't edit by hand.
-- How long each one-off animation a pet uses on its card plays, in seconds, by species id and animation id:
-- measured in the client (an invisible PlayerModel's OnAnimFinished), since the card's actor can't say when an
-- animation ends. A move that isn't here plays for Moves.T's fixed time.
ns.AnimLengths = {
]] .. table.concat(lines, "\n") .. (#lines > 0 and "\n" or "") .. "}\n")
f:close()
print(("Data/AnimLengths.lua: %d species, %d lengths (%d left out: none, or Stand's)"):format(#lines, kept, dropped))
